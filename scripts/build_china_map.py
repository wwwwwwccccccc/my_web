"""Build a compact SVG path set for the China province map."""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "china-provinces.geojson"
OUT = ROOT / "src" / "data" / "chinaMap.ts"

W, H = 1000, 640
PAD = 24
LON_MIN, LON_MAX = 73.5, 135.1
LAT_MIN, LAT_MAX = 17.5, 53.6

NAMES = {
    110000: "北京", 120000: "天津", 130000: "河北", 140000: "山西", 150000: "内蒙古",
    210000: "辽宁", 220000: "吉林", 230000: "黑龙江", 310000: "上海", 320000: "江苏",
    330000: "浙江", 340000: "安徽", 350000: "福建", 360000: "江西", 370000: "山东",
    410000: "河南", 420000: "湖北", 430000: "湖南", 440000: "广东", 450000: "广西",
    460000: "海南", 500000: "重庆", 510000: "四川", 520000: "贵州", 530000: "云南",
    540000: "西藏", 610000: "陕西", 620000: "甘肃", 630000: "青海", 640000: "宁夏",
    650000: "新疆", 710000: "台湾", 810000: "香港", 820000: "澳门",
}


def project(lon, lat):
    scale = min((W - PAD * 2) / (LON_MAX - LON_MIN), (H - PAD * 2) / (LAT_MAX - LAT_MIN))
    x = (lon - LON_MIN) * scale + (W - (LON_MAX - LON_MIN) * scale) / 2
    y = (LAT_MAX - lat) * scale + (H - (LAT_MAX - LAT_MIN) * scale) / 2
    return x, y


def area(points):
    a = 0.0
    for i in range(len(points)):
        x1, y1 = points[i]
        x2, y2 = points[(i + 1) % len(points)]
        a += x1 * y2 - x2 * y1
    return abs(a) / 2


def rdp(points, epsilon):
    if len(points) < 3:
        return points
    start, end = points[0], points[-1]
    dx, dy = end[0] - start[0], end[1] - start[1]
    norm = math.hypot(dx, dy)
    best, index = -1.0, 0
    for i in range(1, len(points) - 1):
        p = points[i]
        if norm == 0:
            d = math.hypot(p[0] - start[0], p[1] - start[1])
        else:
            d = abs(dy * p[0] - dx * p[1] + end[0] * start[1] - end[1] * start[0]) / norm
        if d > best:
            best, index = d, i
    if best > epsilon:
        left = rdp(points[: index + 1], epsilon)
        right = rdp(points[index:], epsilon)
        return left[:-1] + right
    return [start, end]


def rings(geometry):
    if geometry["type"] == "Polygon":
        return geometry["coordinates"]
    if geometry["type"] == "MultiPolygon":
        out = []
        for poly in geometry["coordinates"]:
            out.extend(poly)
        return out
    return []


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    provinces = []
    for feature in data["features"]:
        props = feature.get("properties", {})
        code = props.get("adcode")
        if code == 100000 or code == "100000_JD":
            continue
        name = NAMES.get(code)
        if not name:
            continue
        center = props.get("center") or props.get("centroid") or [0, 0]
        paths = []
        for ring in rings(feature["geometry"]):
            # Drop the far South China Sea islets; keep Hainan / Taiwan / HK / Macau.
            if max(lat for _, lat in ring) < LAT_MIN:
                continue
            pts = [project(lon, lat) for lon, lat in ring]
            if area(pts) < 0.6:
                continue
            pts = rdp(pts, 0.4)
            if len(pts) < 3:
                continue
            paths.append(pts)
        if not paths:
            continue
        d = " ".join(
            "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in ring) + " Z" for ring in paths
        )
        lx, ly = project(center[0], center[1])
        provinces.append({
            "code": str(code),
            "name": name,
            "d": d,
            "label": [round(lx, 1), round(ly, 1)],
        })

    lines = [
        "// Generated by scripts/build_china_map.py from DataV China GeoJSON.",
        "// Simplified for the portfolio map; replace the GeoJSON and rerun if needed.",
        "export type ChinaProvinceShape = {",
        "  code: string",
        "  name: string",
        "  d: string",
        "  label: [number, number]",
        "}",
        "",
        "export const chinaMapViewBox = '0 0 1000 640'",
        "",
        "export const chinaProvinces: ChinaProvinceShape[] = [",
    ]
    for p in provinces:
        d = p["d"].replace("\\", "\\\\").replace("'", "\\'")
        lines.append("  {")
        lines.append(f"    code: '{p['code']}',")
        lines.append(f"    name: '{p['name']}',")
        lines.append(f"    d: '{d}',")
        lines.append(f"    label: [{p['label'][0]}, {p['label'][1]}],")
        lines.append("  },")
    lines.append("]")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes, {len(provinces)} provinces)")


if __name__ == "__main__":
    main()
